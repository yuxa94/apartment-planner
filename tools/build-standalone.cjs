// Builds one self-contained HTML file of this stage (CSS, scripts and unit plans inlined) that opens without a server:
// double-click it, or upload it to Claude or ChatGPT and show it as an artifact / canvas preview.
// Usage: node tools/build-standalone.cjs [output]   (default dist/planby-building-plan.html)
const fs = require('fs'), path = require('path'), { execSync } = require('child_process');
const root = path.join(__dirname, '..'), read = f => fs.readFileSync(path.join(root, f), 'utf8');
const out = path.resolve(root, process.argv[2] || 'dist/planby-building-plan.html');

// Inline text must not close its own tag early.
const safeScript = js => js.replace(/<\/script/gi, '<\/script').replace(/<!--/g, '<\!--');
const safeStyle = css => css.replace(/<\/style/gi, '<\/style');

let html = read('index.html');
const plans = ['unit-plans/unit-59.json', 'unit-plans/unit-74.json', 'unit-plans/unit-84.json'].map(f => JSON.parse(read(f)));
let commit = '';
try {
  commit = execSync('git rev-parse --short HEAD', { cwd: root }).toString().trim();
  // Uncommitted changes in the inlined sources make the stamp say so.
  const dirty = execSync('git status --porcelain -- index.html style.css stage.js engine.js state.js units.js app.js unit-plans', { cwd: root }).toString().trim();
  if (dirty) commit += '+작업중변경';
} catch (e) { commit = 'unknown'; }
const stamp = `<!-- PLANBY building-plan (stage 2) single-file build · commit ${commit} · ${new Date().toISOString()} · generated by tools/build-standalone.cjs, do not edit by hand -->`;

const linkRe = /<link rel="stylesheet" href="([^"]+)">/g, scriptRe = /<script src="([^"]+)"><\/script>/g;
let missing = [];
html = html.replace(linkRe, (_, href) => { try { return `<style>\n${safeStyle(read(href))}\n</style>`; } catch (e) { missing.push(href); return ''; } });
let first = true;
html = html.replace(scriptRe, (_, src) => {
  let body;
  try { body = read(src); } catch (e) { missing.push(src); return ''; }
  // Unit plans go in front of the first script so the app finds them before it starts.
  const pre = first ? `<script>\nwindow.PLANBY_UNIT_PLANS = ${safeScript(JSON.stringify(plans))};\n</script>\n` : '';
  first = false;
  return `${pre}<script data-src="${src}">\n${safeScript(body)}\n</script>`;
});
if (missing.length) throw new Error('missing files: ' + missing.join(', '));
if (/<script src=|<link rel="stylesheet"/.test(html)) throw new Error('an external reference was left in the page');
html = html.replace(/^<!doctype html>/i, `<!doctype html>\n${stamp}`);

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, html);
console.log(`${path.relative(root, out)} · ${(Buffer.byteLength(html) / 1024).toFixed(0)} KB · commit ${commit}`);
